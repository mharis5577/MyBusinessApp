export const QUICK_THEMES_KEY = 'elite_quick_theme_pair';

export function getQuickThemes() {
  try {
    const raw = localStorage.getItem(QUICK_THEMES_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length === 2) {
        return parsed;
      }
    }
  } catch (_) {}
  return ['chocolatier', 'dark'];
}

export function saveQuickThemes(pair) {
  try {
    if (Array.isArray(pair) && pair.length === 2) {
      localStorage.setItem(QUICK_THEMES_KEY, JSON.stringify(pair));
    }
  } catch (_) {}
}

export function getNextQuickTheme(currentTheme, pair = null) {
  const [t1, t2] = pair || getQuickThemes();
  if (currentTheme === t1) return t2;
  return t1;
}

/**
 * Instantly applies a theme by disabling CSS transitions across the DOM
 * during the switch, preventing multi-element transition lag / jank.
 */
let themeSwitchTimer = null;

export function applyTheme(nextTheme) {
  if (!nextTheme || typeof document === 'undefined') return;

  const root = document.documentElement;
  root.classList.add('theme-switching');

  root.setAttribute('data-theme', nextTheme);
  try {
    localStorage.setItem('theme', nextTheme);
  } catch (_) {}

  // Force a synchronous recalc so the new theme paints in one frame.
  void root.offsetHeight;

  // A timer rather than rAF, so the class is cleared even in a hidden tab.
  clearTimeout(themeSwitchTimer);
  themeSwitchTimer = setTimeout(() => {
    root.classList.remove('theme-switching');
    themeSwitchTimer = null;
  }, 60);
}